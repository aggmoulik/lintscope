'use client';

import { STUDIO_DISCOVERY_PORTS } from '@lintscope/api-schema';
import { LintDashboard } from '@lintscope/ui';
import { useSearchParams } from 'next/navigation';
import { useCallback, useEffect, useMemo, useState } from 'react';
import { StudioAuthError, StudioConnectionError, studioApi } from '../_lib/api-client';
import {
  type ParsedStudioParams,
  parseConnectionParams,
  type StudioConnection,
  type StudioTarget,
} from '../_lib/connection';
import { useStudioData } from '../_lib/use-studio-data';
import { ConnectionError } from './connection-error';
import { ConnectionPending } from './connection-pending';

const DEFAULT_HOST = '127.0.0.1';

export function StudioClient() {
  const params = useSearchParams();
  const parsed = useMemo(() => parseConnectionParams(params), [params]);

  if (!parsed.ok) {
    return (
      <ConnectionError
        title="Invalid studio URL"
        message={parsed.reason}
        hint="This URL is generated by the lintscope CLI. If you hand-edited it, double-check the params."
        showCommand
      />
    );
  }

  return <StudioConnector params={parsed.params} />;
}

type ResolveState =
  | { kind: 'resolving' }
  | { kind: 'ready'; connection: StudioConnection }
  | { kind: 'error'; error: unknown };

/**
 * Resolve a full connection from the URL params:
 *  - `port` given → handshake at that host:port (token from URL or handshake);
 *  - `port` absent → probe the discovery range, handshaking each until one
 *    answers. The token is never read from the URL when absent.
 */
async function resolveConnection(params: ParsedStudioParams): Promise<StudioConnection> {
  const host = params.host ?? DEFAULT_HOST;
  const withName = (t: StudioTarget): StudioTarget =>
    params.name ? { ...t, name: params.name } : t;

  if (params.port) {
    const target = withName({ host, port: params.port });
    const token = params.token ?? (await studioApi.handshake(target)).token;
    return { ...target, token };
  }

  let lastError: unknown;
  for (const port of STUDIO_DISCOVERY_PORTS) {
    const target = withName({ host, port: String(port) });
    try {
      const hs = await studioApi.handshake(target);
      return { ...target, token: hs.token, name: hs.name };
    } catch (err) {
      lastError = err;
    }
  }
  throw new StudioConnectionError(
    `No lintscope studio found on ports ${STUDIO_DISCOVERY_PORTS[0]}–${STUDIO_DISCOVERY_PORTS.at(-1)}. Is the CLI running?`,
    lastError,
  );
}

function useResolvedConnection(params: ParsedStudioParams): ResolveState {
  const [state, setState] = useState<ResolveState>({ kind: 'resolving' });

  useEffect(() => {
    let cancelled = false;
    setState({ kind: 'resolving' });
    resolveConnection(params)
      .then((connection) => {
        if (!cancelled) setState({ kind: 'ready', connection });
      })
      .catch((error: unknown) => {
        if (!cancelled) setState({ kind: 'error', error });
      });
    return () => {
      cancelled = true;
    };
    // `params` is a stable reference (parsed via useMemo on the search params).
  }, [params]);

  return state;
}

function StudioConnector({ params }: { params: ParsedStudioParams }) {
  const resolved = useResolvedConnection(params);

  if (resolved.kind === 'resolving') return <ConnectionPending />;
  if (resolved.kind === 'error') return <HandshakeError error={resolved.error} />;
  return <StudioBody connection={resolved.connection} />;
}

function HandshakeError({ error }: { error: unknown }) {
  if (error instanceof StudioAuthError) {
    return (
      <ConnectionError
        title="Studio server rejected this origin"
        message="The CLI server didn't recognize this page's origin, so it wouldn't hand over the session token."
        hint="Make sure the CLI's --allow-origin matches this site, then reopen the studio from the URL it printed."
        showCommand={false}
      />
    );
  }
  if (error instanceof StudioConnectionError) {
    return (
      <ConnectionError
        title="Couldn't reach the studio"
        message={error.message}
        hint="Your `lintscope` CLI may have exited. Restart it and reopen the studio from the URL it prints."
      />
    );
  }
  return (
    <ConnectionError
      title="Couldn't start the studio session"
      message={error instanceof Error ? error.message : String(error)}
      hint="Try reopening the studio from the URL the CLI printed."
      showCommand={false}
    />
  );
}

function StudioBody({ connection }: { connection: StudioConnection }) {
  const { state } = useStudioData(connection);
  const fetchSource = useCallback(
    (relativePath: string) => studioApi.file(connection, relativePath),
    [connection],
  );

  if (state.kind === 'pending') {
    return <ConnectionPending />;
  }

  if (state.kind === 'auth-error') {
    return (
      <ConnectionError
        title="Token rejected by studio server"
        message="The CLI created a single-use token. Was this URL hand-edited, or is an older browser tab still open?"
        hint={`Close this tab and reopen the studio from a fresh \`${connection.host ?? 'localhost'}\` CLI run.`}
      />
    );
  }

  if (state.kind === 'connection-error') {
    return (
      <ConnectionError
        title="Couldn't reach the studio"
        message={state.message}
        hint="Your `lintscope` CLI may have exited. Restart it and reopen the studio from the URL it prints."
      />
    );
  }

  if (state.kind === 'schema-error') {
    return (
      <ConnectionError
        title="Studio server returned an unexpected shape"
        message={`Endpoint ${state.endpoint}: ${state.details}`}
        hint="Your CLI version may be newer or older than this hosted UI. Try `npm i -g lintscope@latest`."
        showCommand={false}
      />
    );
  }

  // state.kind === 'ready' — LintDashboard owns the full chrome (top bar + shell).
  return (
    <LintDashboard
      report={state.report}
      {...(state.init.capabilities.file ? { onFetchSource: fetchSource } : {})}
    />
  );
}
